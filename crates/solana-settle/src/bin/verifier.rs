//! Standalone Merkle inclusion proof verifier CLI for TrustLedger transfers.
//!
//! Allows anyone (auditor, client, regulator) to cryptographically verify that a
//! transfer is included in an on-chain settlement batch without trusting the operator.

use std::path::PathBuf;
use std::process::ExitCode;

use clap::Parser;
use merkle::{Hash32, MmrProof};
use solana_settle::client::TransferReceipt;

/// Command line arguments for the standalone verifier CLI.
#[derive(Parser, Debug)]
#[command(
    name = "verifier",
    about = "TrustLedger Standalone Cryptographic Verifier",
    version = "0.1.0"
)]
struct Cli {
    /// Path to a JSON receipt file generated by the ledger or demo app.
    #[arg(short, long)]
    receipt: Option<PathBuf>,

    /// Expected 64-char hex Merkle root committed on-chain.
    #[arg(long)]
    root: Option<String>,

    /// 64-char hex SHA-256 leaf hash of the transfer.
    #[arg(long)]
    leaf: Option<String>,

    /// Path to binary or JSON proof file.
    #[arg(long)]
    proof_file: Option<PathBuf>,
}

fn main() -> ExitCode {
    let args = Cli::parse();

    println!("============================================================");
    println!("       TrustLedger Cryptographic Settlement Verifier        ");
    println!("============================================================");

    if let Some(receipt_path) = args.receipt {
        verify_receipt_file(&receipt_path)
    } else if let (Some(root_hex), Some(leaf_hex), Some(proof_path)) =
        (args.root, args.leaf, args.proof_file)
    {
        verify_direct_args(&root_hex, &leaf_hex, &proof_path)
    } else {
        eprintln!("[ERROR] Either --receipt <PATH> or all of (--root, --leaf, --proof-file) must be provided.");
        eprintln!("Run `verifier --help` for usage details.");
        ExitCode::FAILURE
    }
}

fn verify_receipt_file(path: &PathBuf) -> ExitCode {
    println!("Loading receipt from: {}", path.display());

    let receipt = match TransferReceipt::load_from_file(path) {
        Ok(r) => r,
        Err(e) => {
            eprintln!("[FAILED] Failed to load receipt: {e}");
            return ExitCode::FAILURE;
        }
    };

    println!("------------------------------------------------------------");
    println!("Transfer Details:");
    println!("  Transfer ID:    {}", receipt.transfer_id);
    println!("  Debit Account:  {}", receipt.debit_account);
    println!("  Credit Account: {}", receipt.credit_account);
    println!("  Amount (units): {}", receipt.amount);
    println!("  Batch Sequence: {}", receipt.batch_seq);
    println!("  Merkle Root:    {}", receipt.merkle_root);
    println!("  Leaf Hash:      {}", receipt.leaf_hash);
    println!(
        "  Proof Path:     {} siblings, {} mountain peaks",
        receipt.proof.siblings.len(),
        receipt.proof.peaks.len()
    );
    println!("------------------------------------------------------------");

    match receipt.verify() {
        Ok(()) => {
            println!(
                "\x1b[32;1m[VERIFIED]\x1b[0m Cryptographic proof matches on-chain Merkle root!"
            );
            println!(
                "Status: Transfer is immutably included in settlement batch {}.",
                receipt.batch_seq
            );
            ExitCode::SUCCESS
        }
        Err(e) => {
            eprintln!("\x1b[31;1m[FAILED]\x1b[0m Verification failed: {e}");
            ExitCode::FAILURE
        }
    }
}

fn verify_direct_args(root_hex: &str, leaf_hex: &str, proof_path: &PathBuf) -> ExitCode {
    let expected_root = match Hash32::from_hex(root_hex) {
        Ok(h) => h,
        Err(e) => {
            eprintln!("[FAILED] Invalid root hex string: {e}");
            return ExitCode::FAILURE;
        }
    };

    let leaf_hash = match Hash32::from_hex(leaf_hex) {
        Ok(h) => h,
        Err(e) => {
            eprintln!("[FAILED] Invalid leaf hex string: {e}");
            return ExitCode::FAILURE;
        }
    };

    let proof_bytes = match std::fs::read(proof_path) {
        Ok(b) => b,
        Err(e) => {
            eprintln!("[FAILED] Failed to read proof file: {e}");
            return ExitCode::FAILURE;
        }
    };

    let proof = match MmrProof::from_bytes(&proof_bytes) {
        Ok(p) => p,
        Err(_) => {
            // Fallback: try reading as JSON
            match serde_json::from_slice::<MmrProof>(&proof_bytes) {
                Ok(p) => p,
                Err(e) => {
                    eprintln!(
                        "[FAILED] Failed to deserialize proof (tried postcard and json): {e}"
                    );
                    return ExitCode::FAILURE;
                }
            }
        }
    };

    match proof.verify(&expected_root, &leaf_hash) {
        Ok(()) => {
            println!(
                "\x1b[32;1m[VERIFIED]\x1b[0m Inclusion proof verified successfully against root!"
            );
            ExitCode::SUCCESS
        }
        Err(e) => {
            eprintln!("\x1b[31;1m[FAILED]\x1b[0m Proof verification failed: {e}");
            ExitCode::FAILURE
        }
    }
}
